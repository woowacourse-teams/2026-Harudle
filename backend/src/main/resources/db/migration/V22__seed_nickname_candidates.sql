combinations AS (
    SELECT adjectives.word || ' ' || animals.word AS nickname
    FROM adjectives CROSS JOIN animals
),
new_candidates AS (
    SELECT combinations.nickname
    FROM combinations
    WHERE NOT EXISTS (
        SELECT 1 FROM nickname_candidates existing
        WHERE existing.nickname = combinations.nickname
    )
),
shuffled_candidates AS (
    SELECT nickname, ROW_NUMBER() OVER (ORDER BY random(), nickname) AS new_order
    FROM new_candidates
),
last_order AS (
    SELECT COALESCE(MAX(allocation_order), 0) AS value FROM nickname_candidates
)
INSERT INTO nickname_candidates (nickname, allocation_order, assigned_user_id)
SELECT candidate.nickname, last_order.value + candidate.new_order, users.id
FROM shuffled_candidates candidate
CROSS JOIN last_order
LEFT JOIN users ON users.nickname = candidate.nickname AND users.deleted_at IS NULL
ON CONFLICT (nickname) DO NOTHING;
